// Ports Mascot Designer's movement library (runtime/motion.json) to plain CSS
// keyframes, so the star can play the same moves with no JavaScript runtime.
//
//   node scripts/mascot/moves-to-css.mjs <path/to/motion.json> > src/styles/mascot-moves.css
//
// Each move becomes up to three animations on the individual transform
// properties (scale, rotate, translate), one per track, so every track keeps
// its own key times and easing exactly as authored.
import fs from "node:fs";

const motion = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));

// The library's easings as cubic-beziers. `in` (t²) and `out` (1-(1-t)²) are exact;
// `inOut` (a cosine) is the standard sine in-out curve.
const EASE = {
  linear: "linear",
  in: "cubic-bezier(0.333, 0, 0.667, 0.333)",
  out: "cubic-bezier(0.333, 0.667, 0.667, 1)",
  inOut: "cubic-bezier(0.37, 0, 0.63, 1)",
};

const num = (v) => String(+v.toFixed(4));
const pct = (t, d) => `${+((t / d) * 100).toFixed(3)}%`;

/** keys: [[time, value, easeIntoThisKey?], ...] with value possibly a tuple. */
function keyframes(name, keys, duration, declare) {
  const ks = keys.map(([t, v, e]) => ({ t, v, e }));
  if (ks[0].t > 0) ks.unshift({ t: 0, v: ks[0].v });
  if (ks[ks.length - 1].t < duration) ks.push({ t: duration, v: ks[ks.length - 1].v });
  const lines = ks.map((k, i) => {
    const next = ks[i + 1];
    const ease = next ? ` animation-timing-function: ${EASE[next.e || "linear"]};` : "";
    return `  ${pct(k.t, duration)} { ${declare(k.v)};${ease} }`;
  });
  return `@keyframes ${name} {\n${lines.join("\n")}\n}`;
}

function zip(a, b, fallback) {
  // sx and sy always share key times in this library; fail loudly if that ever changes.
  if (!a) return b.map(([t, v, e]) => [t, [fallback, v], e]);
  if (!b) return a.map(([t, v, e]) => [t, [v, fallback], e]);
  if (a.length !== b.length || a.some((k, i) => k[0] !== b[i][0] || k[2] !== b[i][2])) {
    throw new Error("scale tracks do not share key times");
  }
  return a.map(([t, v, e], i) => [t, [v, b[i][1]], e]);
}

const out = [];
const animations = {};

function port(id, def, duration = def.duration) {
  const tr = def.tracks;
  const parts = [];
  if (tr.sx || tr.sy) {
    const name = `mz-${id}-scale`;
    out.push(keyframes(name, zip(tr.sx, tr.sy, 1), duration, ([x, y]) => `scale: ${num(x)} ${num(y)}`));
    parts.push(name);
  }
  if (tr.rot) {
    const name = `mz-${id}-rotate`;
    out.push(keyframes(name, tr.rot, duration, (v) => `rotate: ${num(v)}deg`));
    parts.push(name);
  }
  if (tr.tx || tr.ty) {
    const name = `mz-${id}-translate`;
    const keys = tr.tx ? tr.tx.map(([t, v, e]) => [t, [v, 0], e]) : tr.ty.map(([t, v, e]) => [t, [0, v], e]);
    if (tr.tx && tr.ty) throw new Error("tx and ty together are not handled");
    out.push(keyframes(name, keys, duration, ([x, y]) => `translate: ${num(x * 100)}% ${num(y * 100)}%`));
    parts.push(name);
  }
  animations[id] = { parts, duration };
}

for (const id of ["idle", "appear", "hello", "celebrate", "oops"]) port(id, motion.states[id]);
port("poke", motion.poke);

const list = (id, extra = "") => animations[id].parts.map((p) => `${p} ${num(animations[id].duration)}s linear ${extra}`.trim()).join(", ");
const ground = "50% 98.2%"; // the feet, measured on the sticker cut-out

console.log(`/*
 * Mascot moves. Generated by scripts/mascot/moves-to-css.mjs from
 * Mascot Designer's movement library (motion.json, version ${motion.version}). Do not edit by hand.
 *
 * Squash and stretch around the feet, anticipation before a jump, overshoot and
 * settle after. One element (.mascot-rig) plays the move; a child (.mascot-poke)
 * adds the tap squish on top.
 */
.mascot-rig,
.mascot-poke {
  display: block;
  transform-origin: ${ground};
}
.mascot-rig[data-move="idle"] {
  animation: ${list("idle", "infinite")};
}
/* First appearance: pop in, then settle into the idle loop without any script. */
.mascot-rig[data-move="enter"] {
  animation:
    ${list("appear", "var(--mascot-delay, 0s) both")},
    ${animations.idle.parts.map((p) => `${p} ${num(animations.idle.duration)}s linear calc(var(--mascot-delay, 0s) + ${num(animations.appear.duration)}s) infinite`).join(",\n    ")};
}
.mascot-rig[data-move="hello"] {
  animation: ${list("hello", "both")};
}
.mascot-rig[data-move="celebrate"] {
  animation: ${list("celebrate", "both")};
}
.mascot-rig[data-move="oops"] {
  animation: ${list("oops", "both")};
}
.mascot-poke[data-poke] {
  animation: ${list("poke")};
}

${out.join("\n\n")}

@media (prefers-reduced-motion: reduce) {
  .mascot-rig,
  .mascot-poke {
    animation: none !important;
  }
}`);
